// capturingNormalizerPublisher records what the normalizer would have put on
// odds.normalized. It stands in for the BUS and for no data: every record it
// captures was generated by the real adapter and mapped by the real mapper.
type capturingNormalizerPublisher struct {
	records []normalizer.NormalizedMarket
}

func (p *capturingNormalizerPublisher) PublishNormalized(_ context.Context, _ domain.MarketID, msg kafka.Message) error {
	if rec, ok := msg.Payload.(normalizer.NormalizedMarket); ok {
		p.records = append(p.records, rec)
	}
	return nil
}

// coldSnapshotter stands in for a compacted topic with nothing on it, which is
// the correct state for a normalizer that has never run.
type coldSnapshotter struct{}

func (coldSnapshotter) Read(context.Context, func(context.Context, *kafka.Delivery) error) (kafka.SnapshotStats, error) {
	return kafka.SnapshotStats{}, nil
}

// realMarkets returns priced markets computed from the synthetic feed, capped at
// limit so the test stays quick.
//
// The clock is fixed because the generator's determinism contract is stated over
// clock readings — "two adapters given the same seed and the same instants must
// produce byte-identical snapshots" — so this fixture is reproducible run to run.
func realMarkets(t *testing.T, limit int) []pricing.ComputedMarket {
	t.Helper()

	now := time.Date(2026, 8, 19, 19, 0, 0, 0, time.UTC)
	adapter, err := synthetic.New(synthetic.Options{
		Seed:  20260819,
		Clock: func() time.Time { return now },
	})
	if err != nil {
		t.Fatalf("synthetic.New: %v", err)
	}

	ctx := context.Background()
	cat, err := adapter.Catalogue(ctx)
	if err != nil {
		t.Fatalf("Catalogue: %v", err)
	}

	decoder, err := normalizer.NewNeutralDecoder(kafka.Provider(provider.NameSynthetic))
	if err != nil {
		t.Fatalf("NewNeutralDecoder: %v", err)
	}
	pub := &capturingNormalizerPublisher{}
	norm, err := normalizer.New(normalizer.Options{
		Provider:    kafka.Provider(provider.NameSynthetic),
		Decoder:     decoder,
		Producer:    pub,
		Snapshotter: coldSnapshotter{},
		Logger:      testLogger(),
		Clock:       func() time.Time { return now },
	})
	if err != nil {
		t.Fatalf("normalizer.New: %v", err)
	}

	for _, league := range cat.Leagues {
		snap, err := adapter.Fetch(ctx, provider.Scope{
			League:  league.ID(),
			Markets: []domain.MarketType{domain.MarketTypeMoneyline},
		})
		if err != nil {
			t.Fatalf("Fetch(%s): %v", league.ID(), err)
		}
		for _, ev := range snap.Events {
			if ev.Raw.IsZero() {
				continue
			}
			d := &kafka.Delivery{
				Topic:     kafka.TopicOddsRawPrefix + provider.NameSynthetic.String(),
				Key:       string(ev.Event.ID()),
				Timestamp: snap.FetchedAt,
				Envelope: kafka.Envelope{
					Version:    kafka.EnvelopeVersion,
					Type:       normalizer.RawMessageType,
					Producer:   "ingest",
					ProducedAt: snap.FetchedAt,
					ObservedAt: ev.Raw.ObservedAt,
					Data:       json.RawMessage(ev.Raw.Body),
				},
			}
			if err := norm.HandleMessage(ctx, d); err != nil {
				t.Fatalf("normalizer.HandleMessage: %v", err)
			}
		}
	}
	if len(pub.records) == 0 {
		t.Fatal("the synthetic feed produced no normalized markets; there is nothing to price")
	}

	// An empty preference list on purpose: the synthetic adapter DESIGNATES its
	// in-house book as the reference, and a market that prices at all is proof
	// that designation travelled the whole pipeline.
	engine, err := pricing.NewEngine(pricing.Options{DevigMethod: odds.MethodPower})
	if err != nil {
		t.Fatalf("pricing.NewEngine: %v", err)
	}

	out := make([]pricing.ComputedMarket, 0, limit)
	for _, rec := range pub.records {
		computed, err := engine.Price(ctx, rec)
		if err != nil {
			continue
		}
		if err := computed.Validate(); err != nil {
			t.Fatalf("the engine produced a record its own validator refuses: %v", err)
		}
		out = append(out, computed)
		if len(out) == limit {
			break
		}
	}
	if len(out) == 0 {
		t.Fatal("the engine refused every market on the synthetic feed")
	}
	return out
}

