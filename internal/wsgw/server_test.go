func TestATokenInTheQueryStringIsRefusedAndSaysWhy(t *testing.T) {
	t.Parallel()

	base, _, reg := gateway(t, realMarkets(t, 1), nil, nil)

	client, _, err := dial(t, base, Route+"?access_token="+sampleToken, nil)
	if err != nil {
		t.Fatalf("dial: %v", err)
	}

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	// The refusal is delivered OVER THE SOCKET, because a browser can read a
	// close reason and can read essentially nothing from a failed handshake. A
	// silent downgrade to anonymous would let the developer watch market data
	// arrive and conclude the URL was fine.
	frame := client.read(ctx)
	if frame.Type != KindError || frame.Code != CodeUnauthorized {
		t.Fatalf("first frame is {%s %s}, want {error unauthorized}", frame.Type, frame.Code)
	}
	if frame.Seq != 1 {
		t.Fatalf("the refusal carries seq %d, want 1 — every frame on every connection "+
			"has a sequence number", frame.Seq)
	}

	_, _, err = client.conn.Read(ctx)
	if got := websocket.CloseStatus(err); got != websocket.StatusPolicyViolation {
		t.Fatalf("the connection closed with status %d, want %d", got, websocket.StatusPolicyViolation)
	}
	if n := counter(t, reg, "sharpline_ws_connections_total", "result", string(ConnectionRejected)); n != 1 {
		t.Fatalf("connections_total{rejected} = %v, want 1", n)
	}
	if n := counter(t, reg, "sharpline_ws_connections_total", "result", string(ConnectionAccepted)); n != 0 {
		t.Fatalf("connections_total{accepted} = %v; a refused credential is not an accepted "+
			"connection", n)
	}
}

