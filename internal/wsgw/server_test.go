func TestGatewayServesTheSnapshotThenDeltaProtocol(t *testing.T) {
	t.Parallel()

	markets := realMarkets(t, 4)
	base, h, _ := gateway(t, markets, nil, nil)

	client, _, err := dial(t, base, Route, nil)
	if err != nil {
		t.Fatalf("dial: %v", err)
	}
	if got := client.conn.Subprotocol(); got != Protocol {
		t.Fatalf("negotiated subprotocol is %q, want %q — a bearer offer must never be "+
			"echoed back into the handshake response", got, Protocol)
	}

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	hello := client.read(ctx)
	if hello.Type != KindHello || hello.Seq != 1 {
		t.Fatalf("first frame is {%s seq %d}, want {hello seq 1}", hello.Type, hello.Seq)
	}
	if hello.Resumed {
		t.Fatal("a fresh anonymous connection claims a resumed session")
	}

	channels, err := ChannelsFor(markets[0])
	if err != nil {
		t.Fatalf("ChannelsFor: %v", err)
	}
	marketChannel := channels[0]

	client.write(ctx, fmt.Sprintf(`{"type":"subscribe","id":"s1","channels":[%q]}`, marketChannel.String()))

	ack := client.read(ctx)
	if ack.Type != KindAck || ack.ID != "s1" {
		t.Fatalf("second frame is {%s id %q}, want {ack s1}", ack.Type, ack.ID)
	}
	if len(ack.Rejected) != 0 {
		t.Fatalf("the ack rejected %+v", ack.Rejected)
	}

	snapshot := client.read(ctx)
	if snapshot.Type != KindSnapshot || snapshot.Channel != marketChannel.String() {
		t.Fatalf("third frame is {%s %s}, want a snapshot of %s",
			snapshot.Type, snapshot.Channel, marketChannel)
	}
	if len(snapshot.Markets) != 1 {
		t.Fatalf("the snapshot carries %d markets, want 1", len(snapshot.Markets))
	}

	// The payload reached the browser BYTE FOR BYTE. It is compared against the
	// bytes the slate holds rather than against a re-marshalling of the struct,
	// because a re-marshal would agree with a gateway that had quietly reshaped
	// the document.
	id, err := markets[0].MarketID()
	if err != nil {
		t.Fatalf("MarketID: %v", err)
	}
	held := h.Store().Snapshot(mustChannel(t, marketChannel.String()))
	if len(held) != 1 {
		t.Fatalf("the slate holds %d markets for %s, want 1", len(held), marketChannel)
	}
	if string(snapshot.Markets[0]) != string(held[0].Payload) {
		t.Fatal("the market document was re-marshalled on its way to the client")
	}

	var received pricing.ComputedMarket
	if err := json.Unmarshal(snapshot.Markets[0], &received); err != nil {
		t.Fatalf("the client received something that is not a ComputedMarket: %v", err)
	}
	if err := received.Validate(); err != nil {
		t.Fatalf("the client received a document that fails the pricer's own validator: %v", err)
	}
	if got, _ := received.MarketID(); got != id {
		t.Fatalf("the client received market %q, want %q", got, id)
	}
	if len(received.Books) == 0 || len(received.Fair.Selections) == 0 {
		t.Fatal("the delivered document has no books or no fair value; it did not come " +
			"from the pricing engine")
	}

	// A real price change, folded through the same handler the bus drives.
	moved := markets[0]
	moved.SourceFingerprint = "moved"
	moved.ObservedAt = moved.ObservedAt.Add(time.Second)
	moved.IngestedAt = moved.IngestedAt.Add(time.Second)
	if err := h.HandleMessage(ctx, delivery(t, moved, 999)); err != nil {
		t.Fatalf("HandleMessage: %v", err)
	}

	delta := client.read(ctx)
	if delta.Type != KindDelta || delta.Channel != marketChannel.String() {
		t.Fatalf("fourth frame is {%s %s}, want a delta on %s", delta.Type, delta.Channel, marketChannel)
	}
	if fingerprint(t, delta.Market) != "moved" {
		t.Fatal("the delta did not carry the updated document")
	}
	if delta.Seq != snapshot.Seq+1 {
		t.Fatalf("the delta carries seq %d after a snapshot at %d; the sequence must be "+
			"contiguous or a client cannot detect a gap", delta.Seq, snapshot.Seq)
	}

	// A client-requested resync re-bases the client on a fresh snapshot.
	client.write(ctx, `{"type":"resync","id":"r1"}`)
	again := client.read(ctx)
	if again.Type != KindSnapshot || again.ID != "r1" {
		t.Fatalf("resync answered with {%s id %q}, want {snapshot r1}", again.Type, again.ID)
	}
	if fingerprint(t, again.Markets[0]) != "moved" {
		t.Fatal("the resync snapshot carries a stale document")
	}
}

func TestAnonymousIsTheDefaultAndIsAnnouncedAsSuch(t *testing.T) {
	t.Parallel()

	base, _, _ := gateway(t, realMarkets(t, 1), nil, nil)
	client, _, err := dial(t, base, Route, nil)
	if err != nil {
		t.Fatalf("dial: %v", err)
	}

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	var hello struct {
		Type          MessageKind `json:"type"`
		Authenticated bool        `json:"authenticated"`
		Protocol      string      `json:"protocol"`
		ConnectionID  string      `json:"connection_id"`
		Heartbeat     int         `json:"heartbeat_seconds"`
	}
	_, data, err := client.conn.Read(ctx)
	if err != nil {
		t.Fatalf("read: %v", err)
	}
	if err := json.Unmarshal(data, &hello); err != nil {
		t.Fatalf("hello is not JSON: %v", err)
	}
	if hello.Type != KindHello || hello.Authenticated {
		t.Fatalf("hello = {%s authenticated:%v}; market data is public, so an anonymous "+
			"connection is a first-class state", hello.Type, hello.Authenticated)
	}
	if hello.Protocol != Protocol || hello.ConnectionID == "" || hello.Heartbeat <= 0 {
		t.Fatalf("hello is missing its own identity: %+v", hello)
	}
}

