// wsClient wraps a dialled connection with the decoding every test does.
type wsClient struct {
	t    *testing.T
	conn *websocket.Conn
}

func (c *wsClient) read(ctx context.Context) testFrame {
	c.t.Helper()
	typ, data, err := c.conn.Read(ctx)
	if err != nil {
		c.t.Fatalf("read: %v", err)
	}
	if typ != websocket.MessageText {
		c.t.Fatalf("server sent a %v frame; the protocol is JSON text", typ)
	}
	return decodeTestFrame(c.t, data)
}

func (c *wsClient) write(ctx context.Context, raw string) {
	c.t.Helper()
	if err := c.conn.Write(ctx, websocket.MessageText, []byte(raw)); err != nil {
		c.t.Fatalf("write: %v", err)
	}
}

// gateway builds a listener over a hub whose slate already holds the given
// markets, and returns the base URL.
func gateway(
	t *testing.T,
	markets []pricing.ComputedMarket,
	hubOpts func(*HubOptions),
	serverOpts func(*ServerOptions),
) (string, *Hub, *prometheus.Registry) {
	t.Helper()

	records := make([]*kafka.Delivery, 0, len(markets))
	for i, m := range markets {
		records = append(records, delivery(t, m, int64(i)))
	}
	source := newStubSource(records...)

	h, reg := newTestHub(t, func(o *HubOptions) {
		o.Source = source
		// A short drain by default so a test's teardown does not spend the
		// production budget waiting for a client that has already gone. Applied
		// before the caller's override, so a test about the drain can still set
		// its own.
		o.Options.ShutdownDrain = 25 * time.Millisecond
		if hubOpts != nil {
			hubOpts(o)
		}
	})

	runCtx, cancelRun := context.WithCancel(context.Background())
	runDone := make(chan struct{})
	go func() { defer close(runDone); _ = h.Run(runCtx) }()
	<-source.replay
	waitFor(t, func() bool { return h.Check(context.Background()) == nil })

	sopts := ServerOptions{Hub: h}
	if serverOpts != nil {
		serverOpts(&sopts)
	}
	srv, err := NewServer(sopts)
	if err != nil {
		t.Fatalf("NewServer: %v", err)
	}

	mux := http.NewServeMux()
	mux.Handle("GET "+Route, srv)
	ts := httptest.NewServer(mux)

	t.Cleanup(func() {
		shutdownCtx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		_ = h.Shutdown(shutdownCtx)
		ts.Close()
		cancelRun()
		<-runDone
	})

	return ts.URL, h, reg
}

// dial opens a client connection the way a browser would: offering
// "sharpline.v1" and nothing else unless a credential is supplied.
func dial(t *testing.T, base, path string, opts *websocket.DialOptions) (*wsClient, *http.Response, error) {
	t.Helper()
	if opts == nil {
		opts = &websocket.DialOptions{Subprotocols: []string{Protocol}}
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	url := "ws" + strings.TrimPrefix(base, "http") + path
	conn, resp, err := websocket.Dial(ctx, url, opts)
	if err != nil {
		return nil, resp, err
	}
	t.Cleanup(func() { _ = conn.CloseNow() })
	return &wsClient{t: t, conn: conn}, resp, nil
}

