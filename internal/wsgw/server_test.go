// # Where the fixtures come from
//
// Nothing in this file writes a price. [realMarkets] drives the REAL synthetic
// provider through the REAL normalizer and prices the result with the REAL
// pricing engine, which is the same path a record takes from a provider poll to
// price.computed — internal/pricing/synthetic_test.go established the pattern
// and this reuses it. What reaches a client here is therefore a document the
// pricer would actually publish, with margins, per-book bias and tick flooring
// all in play, rather than a plausible-looking literal.
//
// That matters more here than anywhere else in the package: this is the only
// file that asserts on what a BROWSER receives, and a hand-written payload would
// make it a test of this package's imagination.
