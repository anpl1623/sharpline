func TestTheConnectionCeilingRefusesWith503(t *testing.T) {
	t.Parallel()

	base, _, reg := gateway(t, realMarkets(t, 1), nil, func(o *ServerOptions) {
		o.MaxConnections = 1
	})

	first, _, err := dial(t, base, Route, nil)
	if err != nil {
		t.Fatalf("the first dial failed: %v", err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if frame := first.read(ctx); frame.Type != KindHello {
		t.Fatalf("first frame is %s, want hello", frame.Type)
	}

	_, resp, err := dial(t, base, Route, nil)
	if err == nil {
		t.Fatal("a second connection was accepted past the ceiling")
	}
	if resp == nil || resp.StatusCode != http.StatusServiceUnavailable {
		// 503 rather than an accept-then-close: a load balancer's passive health
		// check already understands a 503, and a client with a jittered backoff
		// would read a 1001 close as "try again shortly" rather than "full".
		t.Fatalf("the refusal was %v, want 503", resp)
	}
	if n := counter(t, reg, "sharpline_ws_connections_total", "result", string(ConnectionRejected)); n != 1 {
		t.Fatalf("connections_total{rejected} = %v, want 1", n)
	}
}

func TestAProtocolViolationOverARealSocketClosesTheConnection(t *testing.T) {
	t.Parallel()

	base, _, _ := gateway(t, realMarkets(t, 1), nil, nil)
	client, _, err := dial(t, base, Route, nil)
	if err != nil {
		t.Fatalf("dial: %v", err)
	}

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if frame := client.read(ctx); frame.Type != KindHello {
		t.Fatalf("first frame is %s, want hello", frame.Type)
	}

	client.write(ctx, `{"type":"subscribe","channel":"market:x"}`)

	frame := client.read(ctx)
	if frame.Type != KindError || frame.Code != CodeMalformedFrame {
		t.Fatalf("frame is {%s %s}, want {error malformed_frame}", frame.Type, frame.Code)
	}
	_, _, err = client.conn.Read(ctx)
	if got := websocket.CloseStatus(err); got != websocket.StatusPolicyViolation {
		t.Fatalf("the connection closed with status %d, want %d", got, websocket.StatusPolicyViolation)
	}
}

func TestShutdownReachesARealClient(t *testing.T) {
	t.Parallel()

	base, h, _ := gateway(t, realMarkets(t, 1), func(o *HubOptions) {
		o.Options.ShutdownDrain = 50 * time.Millisecond
	}, nil)

	client, _, err := dial(t, base, Route, nil)
	if err != nil {
		t.Fatalf("dial: %v", err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if frame := client.read(ctx); frame.Type != KindHello {
		t.Fatalf("first frame is %s, want hello", frame.Type)
	}

	// Shutdown runs concurrently with the client's reads, which is the only
	// honest arrangement: it waits for each connection to finish, and a
	// connection cannot finish until the peer has received and acknowledged the
	// close frame. A test that called Shutdown and only then started reading
	// would be modelling a client that has stopped reading — which is a
	// different scenario, and the one the ctx budget and the straggler warning
	// exist for.
	shutdownCtx, shutdownCancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer shutdownCancel()
	shutdownErr := make(chan error, 1)
	go func() { shutdownErr <- h.Shutdown(shutdownCtx) }()

	frame := client.read(ctx)
	if frame.Type != KindError || frame.Code != CodeGoingAway {
		t.Fatalf("frame is {%s %s}, want {error going_away}", frame.Type, frame.Code)
	}
	_, _, err = client.conn.Read(ctx)
	if got := websocket.CloseStatus(err); got != websocket.StatusGoingAway {
		t.Fatalf("the connection closed with status %d, want %d", got, websocket.StatusGoingAway)
	}
	if err := <-shutdownErr; err != nil {
		t.Fatalf("Shutdown: %v", err)
	}
}
