func TestAVerifiedTokenIsAnnouncedInHello(t *testing.T) {
	t.Parallel()

	var seen string
	base, _, _ := gateway(t, realMarkets(t, 1), func(o *HubOptions) {
		o.Options.Verifier = TokenVerifierFunc(func(_ context.Context, token string) (Identity, error) {
			seen = token
			return Identity{UserID: "user-1", SessionID: "family-1", ExpiresAt: time.Now().Add(time.Hour)}, nil
		})
	}, nil)

	client, _, err := dial(t, base, Route, &websocket.DialOptions{
		Subprotocols: []string{Protocol, BearerSubprotocolPrefix + sampleToken},
	})
	if err != nil {
		t.Fatalf("dial: %v", err)
	}

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	var hello struct {
		Type          MessageKind `json:"type"`
		Authenticated bool        `json:"authenticated"`
		SessionID     string      `json:"session_id"`
	}
	_, data, err := client.conn.Read(ctx)
	if err != nil {
		t.Fatalf("read: %v", err)
	}
	if err := json.Unmarshal(data, &hello); err != nil {
		t.Fatalf("hello is not JSON: %v", err)
	}
	if hello.Type != KindHello || !hello.Authenticated {
		t.Fatalf("hello = {%s authenticated:%v}, want an authenticated hello",
			hello.Type, hello.Authenticated)
	}
	if hello.SessionID != "family-1" {
		t.Fatalf("the durable session key is %q, want the token's own session claim", hello.SessionID)
	}
	if seen != sampleToken {
		t.Fatalf("the verifier was handed %q, want the raw token from the subprotocol offer", seen)
	}

	// The token itself must never appear in the handshake response.
	if got := client.conn.Subprotocol(); got != Protocol {
		t.Fatalf("the server echoed %q; echoing the bearer offer writes the client's access "+
			"token into a response header", got)
	}
}

